"""Bell NPC helpers and their boss arenas (party co-op; gpu/shim/party/party_npcfog.inc).

Game data (read-only, untrusted; run with python -I -X utf8). GAME = .../dvdroot_ps4.

  python -I -X utf8 tools/party/npcfog_tool.py gen GAME [--out gpu/shim/party/party_npcfog.inc]
      The Beckoning-Bell NPC helpers' two map events (template xx04450 "walk to the boss room", xx04460
      "go through the fog into the boss room", every map EMEVD, InitializeEvent calls in event 0):
      per NPC chr: its join / leave flags (xx04420 / xx04430), the host-entered flag the walk waits on
      (xx04800), and the boss room's entry spot (the first arena region of the xx04460 call, from the
      map's MSB: POINT_PARAM_ST entry +0x14 position, entity id at the entry + offset q[3]).
"""
import argparse, struct, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import flag_tool as ft  # noqa: E402
import ids_tool as it  # noqa: E402


def calls(event_dir):
    """{map stem: [init args tuple...]} of every InitializeEvent in event 0 whose id ends 4450 / 4460."""
    out = {}
    for stem, p, _eld in ft.event_files(event_dir):
        for e in ft.Emevd(ft.read_maybe_dcx(p)).events:
            if e["id"] != 0:
                continue
            for bank, iid, raw in e["ins"]:
                r = bytes(raw)
                if bank == 2000 and iid == 0 and len(r) >= 8:
                    ints = struct.unpack("<%di" % (len(r) // 4), r)
                    if ints[1] >= 12000000 and ints[1] % 10000 in (4450, 4460):
                        out.setdefault(stem, []).append(ints)
    return out


def regions(msb_path):
    """{entity id: (x, y, z, yaw degrees)} of the MSB's regions."""
    data = ft.read_maybe_dcx(msb_path)
    pts = dict(it.msb_lists(data))["POINT_PARAM_ST"]
    out = {}
    for r in pts:
        q = struct.unpack_from("<4q", data, r + 0x30)
        ent = struct.unpack_from("<i", data, r + q[3])[0]
        x, y, z = struct.unpack_from("<3f", data, r + 0x14)
        yaw = struct.unpack_from("<3f", data, r + 0x20)[1]
        if ent > 0:
            out[ent] = (x, y, z, yaw)
    return out


def rows(game):
    ev = calls(game / "event")
    res = []
    for stem, cl in sorted(ev.items()):
        walk = {c[2]: c for c in cl if c[1] % 10000 == 4450}      # npc -> (slot, ev, npc, region, join, leave, host)
        enter = {c[2]: c for c in cl if c[1] % 10000 == 4460}     # npc -> (slot, ev, npc, region, arena, arena2, anim, flag, arena2)
        msb = game / "map" / "mapstudio" / (stem + ".msb.dcx")
        reg = regions(msb) if msb.exists() else {}
        for npc, w in sorted(walk.items()):
            e = enter.get(npc)
            if not e or e[4] not in reg:
                continue
            x, y, z, yaw = reg[e[4]]
            res.append((stem, npc, w[4], w[5], w[6], e[4], x, y, z, yaw))
    return res


def cmd_gen(a):
    res = rows(Path(a.game))
    lines = ["// Generated by tools/party/npcfog_tool.py gen (do not edit): the Beckoning-Bell NPC helpers of every map.",
             "// {npc entity, join flag, leave flag, host-entered flag, arena entry region, x, y, z, yaw}"]
    for stem, npc, j, l, h, ar, x, y, z, yaw in res:
        lines.append("{%du, %du, %du, %du, %du, %.2ff, %.2ff, %.2ff, %.1ff},  // %s" % (npc, j, l, h, ar, x, y, z, yaw, stem))
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("%d helpers -> %s" % (len(res), a.out))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("game")
    g.add_argument("--out", default="gpu/shim/party/party_npcfog.inc")
    g.set_defaults(fn=cmd_gen)
    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    sys.exit(main() or 0)
