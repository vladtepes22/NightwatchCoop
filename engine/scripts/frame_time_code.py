"""The frame-time patch code for the native start (start/frame_time_code.inc).

bb-start compiles the game's patches itself (start/patches.cpp), without Python, so the machine code
of cloth_time.py, cloth.py, foliage_time.py and air_drag.py goes into it as data: their original
bytes (checked against the eboot first) and their writes. None of it depends on the settings, only
whether each one is applied does. After changing one of those scripts:

    python scripts/frame_time_code.py --write

tests/test_frame_time_code.py fails while start/frame_time_code.inc differs from what they make.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import air_drag  # noqa: E402
import cloth  # noqa: E402
import cloth_time  # noqa: E402
import foliage_time  # noqa: E402
import quit_menu  # noqa: E402

INCLUDE = Path(__file__).resolve().parent.parent / 'start' / 'frame_time_code.inc'

# (name, module, env switch, bbport.ini key or None, needs cloth_time's steady time, original sites)
GROUPS = (
    ('Steady cloth time', cloth_time, 'BB_CLOTH_TIME', None, False,
     ((cloth_time.SITE, cloth_time.SITE_BYTES),)),
    ('Steady cloth', cloth, 'BB_STEADY_CLOTH', 'steady_cloth', True,
     ((cloth.SITE, cloth.SITE_BYTES), (cloth.BEND, cloth.BEND_BYTES), (cloth.BATCH, cloth.BATCH_BYTES))),
    ('Plant sway time', foliage_time, 'BB_FOLIAGE_TIME', None, False,
     ((foliage_time.STORE, foliage_time.STORE_BYTES), (foliage_time.KEPT, foliage_time.KEPT_BYTES))),
    ('Jumps as at 30 FPS', air_drag, 'BB_AIR_DRAG', None, False,
     ((air_drag.SITE, air_drag.SITE_BYTES),)),
)


def hex_literal(data, indent):
    text = bytes(data).hex()
    chunks = [text[i:i + 96] for i in range(0, len(text), 96)] or ['']
    return ('\n' + ' ' * indent).join(f'"{c}"' for c in chunks)


def render():
    lines = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by scripts/frame_time_code.py from cloth_time.py, cloth.py, foliage_time.py and',
        '// air_drag.py (python scripts/frame_time_code.py --write); do not edit by hand.',
        f'constexpr std::uint64_t kPatchCodeEnd = {quit_menu.CODE_END:#x}, kPatchCodePageEnd = {quit_menu.CAVE_END:#x};',
        'const FrameTimeGroup kFrameTimeGroups[] = {',
    ]
    for name, module, env, setting, needs, originals in GROUPS:
        module.check_original(lambda start, end, o=dict(originals): o[start][:end - start])
        lines.append(f'    {{"{name}", "{env}", {f"{chr(34)}{setting}{chr(34)}" if setting else "nullptr"}, '
                     f'{"true" if needs else "false"},')
        lines.append('     {')
        for at, data in originals:
            lines.append(f'         {{{at:#x}, {hex_literal(data, 18)}}},')
        lines.append('     },')
        lines.append('     {')
        for at, data in module.code_writes():
            lines.append(f'         {{{at:#x}, {hex_literal(data, 18)}}},')
        lines.append('     }},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--write', action='store_true', help=f'write {INCLUDE.name} (else print it)')
    a = p.parse_args()
    if a.write:
        INCLUDE.write_text(render(), encoding='utf-8', newline='\n')
        print(f'Wrote {INCLUDE}')
    else:
        sys.stdout.write(render())


if __name__ == '__main__':
    main()
