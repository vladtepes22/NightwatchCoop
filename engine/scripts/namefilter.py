"""Offensive display-name filter, shared by the Nightwatch VPN lobby service, the launcher and Iosefka.

The C++ twin is gpu/shim/party/name_filter.{h,cpp} (used by the game). Both implement the SAME spec, load the SAME data
files (data/name_filter/*) and are run against the same test vectors (tests/name_filter_vectors.txt). Change the
behaviour in both or in neither. Data files can be edited without code changes; the embedded copy
(scripts/namefilter_data.py, generated by tools/name_filter/gen_embed.py) is used when no data folder is found.

Spec (what name_offensive() does):
 1. Characters: ASCII is lower-cased; every other character goes through charmap.tsv (NFKC, casefold, accent removal,
    TR39 look-alikes, invisible and combining characters dropped, punctuation and symbols become separators).
 2. Three views of the result: plain; and two with leetspeak applied (0 o, 1 i or l, 3 e, 4 a, 5 s, 7 t, @ a, $ s,
    ! i, + t, ( c, | i or l). Each view is cut into words at separators; runs of three or more single characters
    (n.i.g or "f a g") are glued into one word. Repeated letters are folded (vowels to one, consonants to two).
 3. Tier A strict terms (strict.txt): a word equal to a term, or (flag s) a term inside the word / across the joined
    words, after the allow list (allow.txt) has cleared ordinary words that contain one.
    Tier B phrases: an identity word (identity.txt, weak ones need a plural or a people word from people.txt) and a
    violence word (violence.txt) in one name, words read inside compounds (blackpplhunter).
    Tier C codes (codes.txt): numeric codes, slogans, symbols.
 4. A name made of upside-down letters is also read reversed, and so is one with a right-to-left embedding or
    override (U+202B, U+202E, U+2067), which displays the stored text backwards.
Non-ASCII scripts that are not look-alikes (Cyrillic, CJK ...) are kept as they are: such names pass unless a term in
that script matches. At most MAX_IN characters of a name are read; the work is bounded by MAX_OUT.
"""
import os

MAX_IN = 80
MAX_OUT = 128
FILES = ("charmap.tsv", "strict.txt", "identity.txt", "people.txt", "violence.txt", "link.txt", "codes.txt", "allow.txt")
MASK_WORD = "Hunter"
VOWELS = "aeiou"
LEET1 = {"0": "o", "1": "i", "3": "e", "4": "a", "5": "s", "7": "t", "@": "a", "$": "s", "!": "i", "+": "t", "(": "c", "|": "i"}
LEET2 = dict(LEET1, **{"1": "l", "|": "l"})
UPSIDE_SWAP = {"u": "n", "n": "u", "d": "p", "p": "d", "b": "q", "q": "b", "m": "w", "w": "m"}
ID_S, ID_W, VIOL_H, VIOL_A, PEOPLE, LINK = 6, 5, 4, 3, 2, 1
MAX_WORD = 40
BIDI_REVERSE = {0x202B, 0x202E, 0x2067}


def _lines(text):
    for ln in text.splitlines():
        ln = ln.strip()
        if ln and not ln.startswith("#"):
            yield ln


def collapse(s):
    """Runs of one character: vowels to one, everything else to at most two."""
    out = []
    run = 0
    for ch in s:
        if out and out[-1] == ch:
            run += 1
            if ch in VOWELS or run >= 2:
                continue
        else:
            run = 0
        out.append(ch)
    return "".join(out)


def collapse1(s):
    """Every run of one character cut to one."""
    out = []
    for ch in s:
        if not out or out[-1] != ch:
            out.append(ch)
    return "".join(out)


def cap3(s):
    out = []
    run = 0
    for ch in s:
        if out and out[-1] == ch:
            run += 1
            if run >= 3:
                continue
        else:
            run = 0
        out.append(ch)
    return "".join(out)


def _load_embedded():
    try:
        from namefilter_data import TEXTS
        return dict(TEXTS)
    except ImportError:
        import importlib.util
        p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "namefilter_data.py")
        if not os.path.exists(p):
            return None
        spec = importlib.util.spec_from_file_location("namefilter_data", p)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return dict(mod.TEXTS)


def find_data_dir():
    here = os.path.dirname(os.path.abspath(__file__))
    cands = [os.environ.get("BB_NAME_FILTER_DIR", ""), os.path.join(here, "name_filter"),
             os.path.join(here, "..", "data", "name_filter"), os.path.join(here, "..", "..", "..", "data", "name_filter")]
    for c in cands:
        if c and os.path.exists(os.path.join(c, "strict.txt")) and os.path.exists(os.path.join(c, "charmap.tsv")):
            return c
    return None


def load_texts(data_dir=None):
    """The data files as {name: text}: from data_dir, else the first data folder found, else the embedded copy."""
    d = data_dir or find_data_dir()
    if d:
        texts = {}
        for f in FILES:
            with open(os.path.join(d, f), encoding="utf-8") as fh:
                texts[f] = fh.read()
        return texts
    return _load_embedded()


class NameFilter:
    def __init__(self, texts):
        self.cm = {}
        for ln in _lines(texts["charmap.tsv"]):
            key, val = ln.split("\t", 1)
            lo, _, hi = key.partition("-")
            lo = int(lo, 16)
            hi = int(hi, 16) if hi else lo
            if val in ("drop", "sep"):
                for cp in range(lo, hi + 1):
                    self.cm[cp] = (val, "")
            else:
                self.cm[lo] = ("up" if val[0] == "^" else "map", val[1:])
        # normal terms are compared with text whose letter runs are cut to one (ragghead = raghead); terms flagged x
        # (doubled letters belong to the word: nigger is not niger) with text whose runs are cut to two, vowels to one.
        self.terms = {1: set(), 2: set()}
        self.terms_s = {1: set(), 2: set()}
        for ln in _lines(texts["strict.txt"]):
            parts = ln.split()
            flag = parts[1] if len(parts) > 1 else "t"
            form = 2 if "x" in flag else 1
            fold = collapse if form == 2 else collapse1
            t = fold(self._term(parts[0], digits=True))
            if not t:
                continue
            self.terms[form].add(t)
            if not t.endswith("s"):
                self.terms[form].add(fold(t + "s"))
            if "s" in flag:
                self.terms_s[form].add(t)
        self.terms_s = {f: sorted(v) for f, v in self.terms_s.items()}
        self.k = {}

        def put(word, cls):
            if word and self.k.get(word, 0) < cls:
                self.k[word] = cls

        for ln in _lines(texts["identity.txt"]):
            w, flag = ln.split()[:2]
            w = self._term(w)
            put(w, ID_S if flag == "S" else ID_W)
            put(collapse(w + "s"), ID_S)
        for ln in _lines(texts["violence.txt"]):
            w, flag = ln.split()[:2]
            put(self._term(w), VIOL_H if flag == "H" else VIOL_A)
        for ln in _lines(texts["people.txt"]):
            put(self._term(ln.split()[0]), PEOPLE)
        for ln in _lines(texts["link.txt"]):
            put(self._term(ln.split()[0]), LINK)
        self.k_max = max(len(w) for w in self.k)
        self.c_join, self.c_raw, self.c_rawjoin, self.c_ctx = [], set(), [], []
        self.c_sym, self.c_sym2 = set(), []
        for ln in _lines(texts["codes.txt"]):
            parts = ln.split()
            kind = parts[0]
            if kind == "join":
                self.c_join.append(self._term(parts[1]))
            elif kind == "raw":
                self.c_raw.add(cap3(self._term(parts[1], digits=True)))
            elif kind == "rawjoin":
                self.c_rawjoin.append(cap3(self._term(parts[1], digits=True)))
            elif kind == "ctx":
                bar = parts.index("|")
                self.c_ctx.append((cap3(self._term(parts[1], digits=True)),
                                   [cap3(self._term(p, digits=True)) for p in parts[bar + 1:]]))
            elif kind == "sym":
                self.c_sym.add(int(parts[1], 16))
            elif kind == "sym2":
                self.c_sym2.append((int(parts[1], 16), int(parts[2], 16)))
        self.allow_w = {1: set(), 2: set()}
        self.allow_c = {1: [], 2: []}
        for ln in _lines(texts["allow.txt"]):
            w, flag = ln.split()[:2]
            for form, fold in ((1, collapse1), (2, collapse)):
                x = fold(self._term(w, digits=True))
                if flag == "w":
                    self.allow_w[form].add(x)
                else:
                    self.allow_c[form].append(x)
        for form in (1, 2):
            self.allow_c[form].sort(key=lambda s: (-len(s), s))

    # ---- characters
    def _map(self, text):
        """-> (list of output code points, number of upside-down letters). Lower case, mapped, separators as 32."""
        out = []
        up = 0
        for ch in text[:MAX_IN]:
            cp = ord(ch)
            if cp < 0x80:
                if 65 <= cp <= 90:
                    cp += 32
                out.append(cp)
            else:
                e = self.cm.get(cp)
                if e is None:
                    out.append(cp)
                elif e[0] == "sep":
                    out.append(32)
                elif e[0] != "drop":
                    out.extend(ord(c) for c in e[1])
                    if e[0] == "up":
                        up += 1
            if len(out) >= MAX_OUT:
                break
        return out[:MAX_OUT], up

    def _term(self, text, digits=False):
        out, _ = self._map(text)
        s = "".join(chr(c) for c in out if c >= 0x80 or chr(c).isalnum())
        return s if digits else collapse(s)

    # ---- views
    @staticmethod
    def _words(cps, leet):
        words, cur = [], []
        for cp in cps:
            ch = chr(cp)
            if leet is not None and ch in leet:
                ch = leet[ch]
            if ("a" <= ch <= "z") or ("0" <= ch <= "9") or cp >= 0x80:
                cur.append(ch)
            elif cur:
                words.append("".join(cur))
                cur = []
        if cur:
            words.append("".join(cur))
        # runs of three or more single characters are one word (n.i.g, f a g)
        merged, i = [], 0
        while i < len(words):
            j = i
            while j < len(words) and len(words[j]) == 1 and words[j] < "\x80":
                j += 1
            if j - i >= 3:
                merged.append("".join(words[i:j]))
                i = j
            else:
                merged.append(words[i])
                i += 1
        return merged

    def _blank(self, w, form):
        if w in self.allow_w[form]:
            return "#"
        for f in self.allow_c[form]:
            if f in w:
                w = w.replace(f, "#")
        return w

    def _dp(self, tok):
        n = len(tok)
        inf = 1 << 30
        best = [inf] * (n + 1)
        best[n] = 0
        for i in range(n - 1, -1, -1):
            for ln in range(1, min(self.k_max, n - i) + 1):
                if tok[i:i + ln] in self.k and best[i + ln] + 1 < best[i]:
                    best[i] = best[i + ln] + 1
        if best[0] >= inf:
            return None
        out, i = [], 0
        while i < n:
            for ln in range(min(self.k_max, n - i), 0, -1):
                w = tok[i:i + ln]
                if w in self.k and best[i + ln] == best[i] - 1:
                    out.append(self.k[w])
                    i += ln
                    break
        return out

    def _elements(self, tok):
        if len(tok) > MAX_WORD or "#" in tok:
            return [0]
        r = self._dp(tok)
        if r is None:
            s = tok.strip("x0123456789")
            if s and s != tok:
                r = self._dp(s)
        return r if r is not None else [0]

    def _tier_a(self, blanked, form):
        terms, terms_s = self.terms[form], self.terms_s[form]
        for b in blanked:
            for part in b.split("#"):
                if not part:
                    continue
                if part in terms or part.strip("x0123456789") in terms:
                    return True
                for t in terms_s:
                    if t in part:
                        return True
        joined = "".join(blanked)
        return any(t in joined for t in terms_s)

    def _tier_b(self, words):
        elems = []
        for w in words:
            elems.extend(self._elements(w))
        strong = weak = va = vh = False
        for i, c in enumerate(elems):
            if c == ID_S or (c == ID_W and i + 1 < len(elems) and elems[i + 1] == PEOPLE):
                strong = True
            elif c == ID_W:
                weak = True
            elif c == VIOL_A:
                va = True
            elif c == VIOL_H:
                vh = True
        return (strong and (va or vh)) or (weak and vh)

    def _scan(self, cps):
        for leet in (None, LEET1, LEET2):
            raw = self._words(cps, leet)
            if self._tier_a([self._blank(collapse1(w), 1) for w in raw], 1):
                return "A"
            words = [collapse(w) for w in raw]
            blanked = [self._blank(w, 2) for w in words]
            if self._tier_a(blanked, 2):
                return "A"
            if self._tier_b(words):
                return "B"
            joined = "".join(blanked)
            if any(j in joined for j in self.c_join):
                return "C"
        return ""

    def _codes(self, cps):
        raw = [cap3(w) for w in self._words(cps, None)]
        rs = set(raw)
        if rs & self.c_raw:
            return True
        joined = "".join(raw)
        if any(j in joined for j in self.c_rawjoin):
            return True
        for tok, others in self.c_ctx:
            if tok in rs and any(o in rs for o in others):
                return True
        return False

    def reason(self, name):
        """'' when the name is fine, else the tier that caught it: 'A' strict, 'B' phrase, 'C' code."""
        if not name:
            return ""
        if isinstance(name, bytes):
            name = name.decode("utf-8", "replace")
        raw = [ord(c) for c in name[:MAX_IN]]
        if set(raw) & self.c_sym:
            return "C"
        for i in range(len(raw) - 1):
            if (raw[i], raw[i + 1]) in self.c_sym2:
                return "C"
        cps, up = self._map(name)
        r = self._scan(cps)
        if r:
            return r
        if self._codes(cps):
            return "C"
        if set(raw) & BIDI_REVERSE:   # a right-to-left override shows the stored text backwards
            r = self._scan(list(reversed(cps)))
            if r:
                return r
        if up >= 1:
            sw = [ord(UPSIDE_SWAP.get(chr(c), chr(c))) for c in reversed(cps)]
            r = self._scan(sw)
            if r:
                return r
        return ""

    def offensive(self, name):
        return bool(self.reason(name))


def fnv1a32(data):
    h = 0x811C9DC5
    for b in data:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def mask_text(name):
    """The replacement shown for an offensive name: stable per name, so two masked players differ ('Hunter 3F2')."""
    if isinstance(name, str):
        name = name.encode("utf-8")
    h = fnv1a32(name)
    return "%s %03X" % (MASK_WORD, (h ^ (h >> 16)) & 0xFFF)


_default = None


def default_filter():
    global _default
    if _default is None:
        texts = load_texts()
        _default = NameFilter(texts) if texts else False
    return _default or None


def name_offensive(name):
    f = default_filter()
    return f.offensive(name) if f else False


def name_reason(name):
    f = default_filter()
    return f.reason(name) if f else ""


def masked_name(name):
    """name, or its mask when it is offensive. Fails open (name unchanged) when no data can be found."""
    return mask_text(name) if name_offensive(name) else name
